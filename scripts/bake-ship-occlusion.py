"""Blender background Python; geometry BVH rays, no images or external assets.
blender -b --python scripts/bake-ship-occlusion.py -- /tmp/ships-for-ao.json src/render/ShipOcclusion.ts
Rebuild input with export-ship-occlusion.mjs first. Deterministic 48-ray cosine
hemisphere, 0.48-world-unit radius; stores 8-bit per-vertex contact shading.
"""
import sys, json, math, base64
from mathutils import Vector
from mathutils.bvhtree import BVHTree
args=sys.argv[sys.argv.index('--')+1:]
ships=json.load(open(args[0])); output={}; manifest={}
for kind,parts in ships.items():
    vertices=[]; faces=[]
    for part in parts:
        offset=len(vertices);p=part['positions'];ix=part['indices']
        vertices += [tuple(p[i:i+3]) for i in range(0,len(p),3)]
        faces += [tuple(offset+k for k in ix[i:i+3]) for i in range(0,len(ix),3)]
    tree=BVHTree.FromPolygons(vertices,faces,all_triangles=True)
    for index,part in enumerate(parts):
        values=[];p=part['positions'];n=part['normals'];cache={}
        for i in range(0,len(p),3):
            key=tuple(round(x,5) for x in p[i:i+3]+n[i:i+3])
            if key in cache: values.append(cache[key]);continue
            normal=Vector(n[i:i+3]).normalized();position=Vector(p[i:i+3])+normal*.006
            tangent=normal.cross(Vector((0,0,1)) if abs(normal.z)<.9 else Vector((0,1,0))).normalized()
            bitangent=normal.cross(tangent);occlusion=0
            for ray in range(48):
                radius=math.sqrt((ray+.5)/48);angle=ray*2.399963229728653
                direction=tangent*(radius*math.cos(angle))+bitangent*(radius*math.sin(angle))+normal*math.sqrt(1-radius*radius)
                hit,_,_,distance=tree.ray_cast(position,direction,.48)
                if hit is not None: occlusion+=(1-distance/.48)**.65
            value=round(255*(1-.56*occlusion/48));values.append(value);cache[key]=value
        key=f'{kind}/{index}';output[key]=base64.b64encode(bytes(values)).decode('ascii');manifest[key]=part['hash']
    print(f'{kind}: {len(vertices)} vertices, {len(faces)} triangles')
with open(args[1],'w') as f:
    f.write('// Generated by scripts/export-ship-occlusion.mjs + bake-ship-occlusion.py.\n// Original geometry contact AO only; not albedo, a screenshot or a billboard.\n')
    f.write('export const SHIP_OCCLUSION:Readonly<Record<string,string>>='+json.dumps(output,separators=(',',':'))+';\n')
    f.write('export const SHIP_OCCLUSION_HASHES:Readonly<Record<string,string>>='+json.dumps(manifest,separators=(',',':'))+';\n')
