import {test,expect} from '@playwright/test';

test('P3/C4: 前景真实边缘岩石、射击边界、窄屏门禁、暂停和 Chromium 截屏',async({page},info)=>{
  const errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('./');
  const stage=page.getByTestId('battlefield');
  await expect(page.getByTestId('webgl-status')).toContainText('WebGL 正常');
  await expect(stage).toHaveAttribute('data-foreground-rocks','2');
  await expect.poll(async()=>Number(await stage.getAttribute('data-foreground-visible'))).toBeGreaterThan(0);
  expect(Number(await stage.getAttribute('data-draw-calls'))).toBeLessThan(72);
  await page.screenshot({path:info.outputPath('p3-c4-safe-foreground-desktop.png'),fullPage:true});
  await page.getByRole('button',{name:'开始',exact:true}).click();
  await page.keyboard.down('ArrowLeft');
  await page.waitForTimeout(1300);
  await page.keyboard.up('ArrowLeft');
  const leftX=Number(await stage.getAttribute('data-player-x'));
  await page.keyboard.down('Space');
  await expect.poll(async()=>Number(await stage.getAttribute('data-bullet-count'))).toBeGreaterThan(0);
  await page.keyboard.up('Space');
  await page.keyboard.down('ArrowRight');
  await page.waitForTimeout(2700);
  await page.keyboard.up('ArrowRight');
  expect(Number(await stage.getAttribute('data-player-x'))).toBeGreaterThan(leftX);
  expect(Number(await stage.getAttribute('data-foreground-visible'))).toBeGreaterThan(0);
  await page.screenshot({path:info.outputPath('p3-c4-edge-combat.png'),fullPage:true});
  await page.getByRole('button',{name:'暂停'}).click();
  const paused=await stage.getAttribute('data-foreground-motion');
  await page.waitForTimeout(170);
  expect(await stage.getAttribute('data-foreground-motion')).toBe(paused);
  await page.setViewportSize({width:390,height:844});
  await expect(stage).toHaveAttribute('data-foreground-visible','0');
  await page.screenshot({path:info.outputPath('p3-c4-portrait-safe.png'),fullPage:true});
  expect(errors).toEqual([]);
});
